import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { IDBFactory, IDBObjectStore as FakeIDBObjectStore } from 'fake-indexeddb';
import { ed25519 } from '@noble/curves/ed25519.js';
import { compareAndSwapSavedVault, decryptSignerVault, decryptSignerVaultWithPasskey, deleteSavedVault, encryptSignerVault, encryptSignerVaultWithPasskey, passkeyVault, readSavedVault, savedVaultMethod, validateSignerVault, writeSavedVault, VAULT_ITERATIONS, type VaultMetadata, type SignerVault } from './vault';
import { bytesToHex } from '@opencaster/protocol/signedKeyRequest';
import { FULL_CLIENT_SCOPES, FULL_SOCIAL_SCOPES } from '@opencaster/client-core/pairing';
import type { PasskeyDescriptor } from './passkey';
import { createCipheriv, pbkdf2Sync } from 'node:crypto';

const PASSWORD = 'synthetic vault passphrase';
const ORIGIN = 'https://opencaster.org';
const key = new Uint8Array(32).fill(19); // synthetic app key, unrelated to custody
const metadata: VaultMetadata = { origin: ORIGIN, fid: 1234, custodyAddress: `0x${'ab'.repeat(20)}`, publicKey: bytesToHex(ed25519.getPublicKey(key)), requestFid: 1234, scopes: [1, 3, 4], ttl: 604800 };
const descriptor = (origin = ORIGIN): PasskeyDescriptor => ({ origin, rpId: new URL(origin).hostname, credentialId: 'c3ludGhldGlj', prfSalt: '23'.repeat(32), userHandle: '34'.repeat(32) });
const secret = new Uint8Array(32).fill(25); // Synthetic PRF fixture, never a real credential.

describe('versioned encrypted device posting-key vault', () => {
  it('keeps a legacy-domain password vault bound to its original authenticated origin', async () => {
    const legacyOrigin = 'https://quorum.arca.computer';
    const legacy = await encryptSignerVault(key, { ...metadata, origin: legacyOrigin }, PASSWORD);
    await expect(decryptSignerVault(legacy, PASSWORD, ORIGIN)).rejects.toThrow('different website');
    const recovered = await decryptSignerVault(legacy, PASSWORD, legacyOrigin);
    expect(recovered.privateKey).toEqual(key); recovered.privateKey.fill(0);
    await expect(decryptSignerVault({ ...legacy, metadata: { ...legacy.metadata, origin: ORIGIN } }, PASSWORD, ORIGIN)).rejects.toThrow('Could not unlock');
  });
  it('decrypts the exact legacy v1 format generated by independent Node PBKDF2/AES primitives', async () => {
    const header: Omit<SignerVault, 'ciphertext'> = { kind: 'arca.hypersnap.device-vault', version: 1, metadata, kdf: { name: 'PBKDF2', hash: 'SHA-256', iterations: VAULT_ITERATIONS, salt: '12'.repeat(16) }, cipher: { name: 'AES-GCM', length: 256, iv: '34'.repeat(12), tagLength: 128 } };
    const material = pbkdf2Sync(PASSWORD, Buffer.from(header.kdf.salt, 'hex'), VAULT_ITERATIONS, 32, 'sha256');
    try {
      const cipher = createCipheriv('aes-256-gcm', material, Buffer.from(header.cipher.iv, 'hex'));
      cipher.setAAD(Buffer.from(JSON.stringify(header)));
      const ciphertext = Buffer.concat([cipher.update(key), cipher.final(), cipher.getAuthTag()]).toString('hex');
      const recovered = await decryptSignerVault({ ...header, ciphertext }, PASSWORD, ORIGIN);
      expect(recovered.privateKey).toEqual(key); recovered.privateKey.fill(0);
    } finally { material.fill(0); }
  });
  it.each([{ selected: FULL_SOCIAL_SCOPES }, { selected: FULL_CLIENT_SCOPES }])('authenticates explicit scope set %j without changing legacy vault compatibility', async ({ selected }) => {
    const expanded = { ...metadata, scopes: [...selected] };
    const vault = await encryptSignerVault(key, expanded, PASSWORD);
    const recovered = await decryptSignerVault(vault, PASSWORD, ORIGIN);
    expect(recovered.metadata.scopes).toEqual(expanded.scopes);
    recovered.privateKey.fill(0);
    await expect(decryptSignerVault({ ...vault, metadata }, PASSWORD, ORIGIN)).rejects.toThrow('Could not unlock');
    await expect(decryptSignerVault({ ...vault, metadata: { ...expanded, scopes: [1, 3, 4, 5, 6, 11, 16] } }, PASSWORD, ORIGIN)).rejects.toThrow('invalid permissions');
  });
  it('encrypts only 32 app-key bytes with independent secure salt/IV and decrypts with authenticated metadata', async () => {
    const first = await encryptSignerVault(key, metadata, PASSWORD);
    const second = await encryptSignerVault(key, metadata, PASSWORD);
    expect(first.kdf).toMatchObject({ name: 'PBKDF2', hash: 'SHA-256', iterations: 600000 });
    expect(VAULT_ITERATIONS).toBe(600000);
    expect(first.kdf.salt).toHaveLength(32);
    expect(first.cipher.iv).toHaveLength(24);
    expect(first.cipher).toMatchObject({ name: 'AES-GCM', length: 256, tagLength: 128 });
    expect(first.kdf.salt).not.toBe(second.kdf.salt);
    expect(first.cipher.iv).not.toBe(second.cipher.iv);
    expect(first.ciphertext).not.toBe(second.ciphertext);
    expect(first.ciphertext).toHaveLength(96); // 32 key bytes + 16-byte GCM tag
    expect(JSON.stringify(first)).not.toContain(bytesToHex(key));
    expect(JSON.stringify(first)).not.toContain(PASSWORD);
    const recovered = await decryptSignerVault(first, PASSWORD, ORIGIN);
    expect(recovered.privateKey).toEqual(key);
    expect(recovered.metadata).toEqual(metadata);
    recovered.privateKey.fill(0);
    expect(key[0]).toBe(19);
  });

  it('rejects wrong passwords, ciphertext tampering, and account metadata substitution', async () => {
    const vault = await encryptSignerVault(key, metadata, PASSWORD);
    await expect(decryptSignerVault(vault, 'wrong synthetic password', ORIGIN)).rejects.toThrow('Could not unlock');
    await expect(decryptSignerVault({ ...vault, ciphertext: `${vault.ciphertext[0] === '0' ? '1' : '0'}${vault.ciphertext.slice(1)}` }, PASSWORD, ORIGIN)).rejects.toThrow('Could not unlock');
    await expect(decryptSignerVault({ ...vault, metadata: { ...vault.metadata, fid: 5678, requestFid: 5678 } }, PASSWORD, ORIGIN)).rejects.toThrow('Could not unlock');
    await expect(decryptSignerVault({ ...vault, metadata: { ...vault.metadata, custodyAddress: `0x${'cd'.repeat(20)}` } }, PASSWORD, ORIGIN)).rejects.toThrow('Could not unlock');
    await expect(decryptSignerVault({ ...vault, kdf: { ...vault.kdf, salt: '00'.repeat(16) } }, PASSWORD, ORIGIN)).rejects.toThrow('Could not unlock');
    await expect(decryptSignerVault({ ...vault, cipher: { ...vault.cipher, iv: '00'.repeat(12) } }, PASSWORD, ORIGIN)).rejects.toThrow('Could not unlock');
  });

  it('rejects unsafe/malformed schemas before unbounded crypto work and scopes the vault to its origin', async () => {
    const vault = await encryptSignerVault(key, metadata, PASSWORD);
    await expect(decryptSignerVault(vault, PASSWORD, 'https://other.example')).rejects.toThrow('different website');
    await expect(decryptSignerVault({ ...vault, version: 2 }, PASSWORD, ORIGIN)).rejects.toThrow('invalid');
    await expect(decryptSignerVault({ ...vault, mnemonic: 'unwanted field' }, PASSWORD, ORIGIN)).rejects.toThrow('invalid');
    await expect(decryptSignerVault({ ...vault, kdf: { ...vault.kdf, iterations: 1e12 } }, PASSWORD, ORIGIN)).rejects.toThrow('invalid');
    await expect(decryptSignerVault({ ...vault, metadata: { ...metadata, scopes: [1, 3, 4, 16] } }, PASSWORD, ORIGIN)).rejects.toThrow('invalid');
    await expect(decryptSignerVault({ ...vault, metadata: { ...metadata, ttl: 0 } }, PASSWORD, ORIGIN)).rejects.toThrow('invalid');
    await expect(decryptSignerVault({ ...vault, ciphertext: 'ff'.repeat(10000) }, PASSWORD, ORIGIN)).rejects.toThrow('invalid');
    await expect(decryptSignerVault({ ...vault, metadata: { ...metadata, origin: `${ORIGIN}/path` } }, PASSWORD, ORIGIN)).rejects.toThrow('invalid origin');
  });

  it('requires a bounded device password and a key matching its claimed public key', async () => {
    await expect(encryptSignerVault(key, metadata, 'short')).rejects.toThrow('12');
    await expect(encryptSignerVault(key, metadata, 'x'.repeat(1025))).rejects.toThrow('1,024');
    await expect(encryptSignerVault(new Uint8Array(32).fill(20), metadata, PASSWORD)).rejects.toThrow('does not match');
    await expect(encryptSignerVault(new Uint8Array(64), metadata, PASSWORD)).rejects.toThrow('does not match');
  });
});

describe('PRF-wrapped device vault v2', () => {
  it('does not move a legacy-domain passkey vault to the canonical domain by rewriting its descriptor', async () => {
    const legacyOrigin = 'https://quorum.arca.computer';
    const legacy = await encryptSignerVaultWithPasskey(key, { ...metadata, origin: legacyOrigin }, descriptor(legacyOrigin), secret);
    await expect(decryptSignerVaultWithPasskey(legacy, secret, ORIGIN, ORIGIN)).rejects.toThrow('different website');
    await expect(decryptSignerVaultWithPasskey({ ...legacy, metadata: { ...legacy.metadata, origin: ORIGIN }, passkey: descriptor() }, secret, ORIGIN, ORIGIN)).rejects.toThrow('Could not unlock');
  });
  it('encrypts a signer with a nonextractable HKDF/AES key and never persists its PRF result', async () => {
    const first = await encryptSignerVaultWithPasskey(key, metadata, descriptor(), secret);
    const second = await encryptSignerVaultWithPasskey(key, metadata, descriptor(), secret);
    expect(first.version).toBe(2); expect(first.kdf).toMatchObject({ name: 'HKDF', hash: 'SHA-256' });
    expect(first.kdf.salt).toHaveLength(64); expect(first.kdf.salt).not.toBe(second.kdf.salt);
    expect(first.cipher.iv).toHaveLength(24); expect(first.cipher.iv).not.toBe(second.cipher.iv);
    expect(first.ciphertext).toHaveLength(96); expect(first.ciphertext).not.toBe(second.ciphertext);
    expect(savedVaultMethod(first)).toBe('passkey');
    const serialized = JSON.stringify(first);
    expect(serialized).not.toContain(bytesToHex(secret)); expect(serialized).not.toContain(bytesToHex(key)); expect(serialized).not.toContain('prfSecret');
    const recovered = await decryptSignerVaultWithPasskey(first, secret, ORIGIN);
    expect(recovered.metadata).toEqual(metadata); expect(recovered.privateKey).toEqual(key); recovered.privateKey.fill(0);
    expect(secret[0]).toBe(25); // Caller owns and wipes its input; the crypto helper wipes its own copy.
  });

  it('authenticates every account, scope, origin, descriptor, salt, IV and ciphertext field', async () => {
    const vault = await encryptSignerVaultWithPasskey(key, metadata, descriptor(), secret);
    const alternatives = [
      { ...vault, metadata: { ...metadata, fid: 4321, requestFid: 4321 } },
      { ...vault, metadata: { ...metadata, custodyAddress: `0x${'cd'.repeat(20)}` } },
      { ...vault, metadata: { ...metadata, publicKey: 'ab'.repeat(32) } },
      { ...vault, metadata: { ...metadata, scopes: [...FULL_CLIENT_SCOPES] } },
      { ...vault, passkey: { ...vault.passkey, credentialId: 'b3RoZXI' } },
      { ...vault, passkey: { ...vault.passkey, prfSalt: 'ab'.repeat(32) } },
      { ...vault, passkey: { ...vault.passkey, userHandle: 'cd'.repeat(32) } },
      { ...vault, kdf: { ...vault.kdf, salt: 'ef'.repeat(32) } },
      { ...vault, cipher: { ...vault.cipher, iv: 'ab'.repeat(12) } },
      { ...vault, ciphertext: `${vault.ciphertext[0] === '0' ? '1' : '0'}${vault.ciphertext.slice(1)}` },
    ];
    for (const altered of alternatives) await expect(decryptSignerVaultWithPasskey(altered, secret, ORIGIN)).rejects.toThrow('Could not unlock');
    await expect(decryptSignerVaultWithPasskey(vault, new Uint8Array(32).fill(26), ORIGIN)).rejects.toThrow('Could not unlock');
    const foreign = 'https://other.arca.computer';
    await expect(decryptSignerVaultWithPasskey({ ...vault, passkey: descriptor(foreign) }, secret, ORIGIN, foreign)).rejects.toThrow('Could not unlock');
    await expect(decryptSignerVaultWithPasskey({ ...vault, metadata: { ...metadata, origin: foreign } }, secret, foreign, ORIGIN)).rejects.toThrow('Could not unlock');
  });

  it('distinguishes the actual local WebAuthn origin from the canonical protocol approval origin', async () => {
    const local = 'http://127.0.0.1:5173';
    const vault = await encryptSignerVaultWithPasskey(key, metadata, descriptor(local), secret);
    const recovered = await decryptSignerVaultWithPasskey(vault, secret, ORIGIN, local);
    expect(recovered.privateKey).toEqual(key); recovered.privateKey.fill(0);
    expect(vault.metadata.origin).toBe(ORIGIN); expect(vault.passkey.origin).toBe(local);
    expect(() => passkeyVault(vault, ORIGIN, ORIGIN)).toThrow();
    expect(() => passkeyVault(vault, 'https://other.example', local)).toThrow('different website');
  });

  it('rejects unknown schemas, algorithms, unbounded fields and absent PRF outputs before deriving a key', async () => {
    const vault = await encryptSignerVaultWithPasskey(key, metadata, descriptor(), secret);
    const derive = vi.spyOn(crypto.subtle, 'deriveKey');
    try {
      for (const altered of [
        { ...vault, version: 3 }, { ...vault, prfSecret: bytesToHex(secret) },
        { ...vault, kdf: { ...vault.kdf, salt: 'ab'.repeat(16) } }, { ...vault, kdf: { ...vault.kdf, iterations: 1 } },
        { ...vault, cipher: { ...vault.cipher, tagLength: 64 } }, { ...vault, passkey: { ...vault.passkey, credentialId: 'a'.repeat(2000) } },
        { ...vault, passkey: { ...vault.passkey, origin: 'http://example.com', rpId: 'example.com' } },
        { ...vault, passkey: { ...vault.passkey, extra: 'secret' } }, { ...vault, metadata: { ...metadata, scopes: [1, 16] } },
      ]) expect(() => validateSignerVault(altered)).toThrow();
      for (const missing of [undefined, new Uint8Array(), new Uint8Array(31), new Uint8Array(64)]) await expect(decryptSignerVaultWithPasskey(vault, missing as Uint8Array, ORIGIN)).rejects.toThrow('32-byte');
      expect(derive).not.toHaveBeenCalled();
    } finally { derive.mockRestore(); }
    await expect(encryptSignerVaultWithPasskey(new Uint8Array(32).fill(20), metadata, descriptor(), secret)).rejects.toThrow('does not match');
    expect(() => passkeyVault(awaitablePasswordFixture(), ORIGIN, ORIGIN)).toThrow('password');
  });
});

function awaitablePasswordFixture(): SignerVault {
  return { kind: 'arca.hypersnap.device-vault', version: 1, metadata, kdf: { name: 'PBKDF2', hash: 'SHA-256', iterations: VAULT_ITERATIONS, salt: '00'.repeat(16) }, cipher: { name: 'AES-GCM', length: 256, iv: '00'.repeat(12), tagLength: 128 }, ciphertext: '00'.repeat(48) };
}

describe('atomic device vault storage', () => {
  beforeEach(() => { vi.stubGlobal('indexedDB', new IDBFactory()); });
  afterEach(() => { vi.restoreAllMocks(); vi.unstubAllGlobals(); });

  async function rawWrite(value: unknown): Promise<void> {
    return new Promise((resolve, reject) => {
      const open = indexedDB.open('arca-hypersnap', 1);
      open.onupgradeneeded = () => open.result.createObjectStore('device-vault');
      open.onerror = () => reject(open.error);
      open.onsuccess = () => {
        const db = open.result;
        const tx = db.transaction('device-vault', 'readwrite');
        tx.objectStore('device-vault').put(value, 'posting-signer');
        tx.oncomplete = () => { db.close(); resolve(); };
        tx.onerror = () => { db.close(); reject(tx.error); };
      };
    });
  }

  function storageFixture(publicKey = metadata.publicKey): SignerVault {
    // Storage schema fixture only: no private key material is present, and this
    // placeholder ciphertext is never decrypted by these transaction tests.
    return {
      kind: 'arca.hypersnap.device-vault', version: 1,
      metadata: { ...metadata, publicKey },
      kdf: { name: 'PBKDF2', hash: 'SHA-256', iterations: VAULT_ITERATIONS, salt: '00'.repeat(16) },
      cipher: { name: 'AES-GCM', length: 256, iv: '00'.repeat(12), tagLength: 128 },
      ciphertext: '00'.repeat(48),
    };
  }

  it('deletes only the requested key and preserves a different session’s vault', async () => {
    const vault = storageFixture();
    await writeSavedVault(vault);
    await deleteSavedVault('ff'.repeat(32));
    expect(await readSavedVault()).toEqual(vault);
    await deleteSavedVault(metadata.publicKey);
    expect(await readSavedVault()).toBeUndefined();
  });

  it('preserves a new tab’s replacement saved while matching-key cleanup runs', async () => {
    const oldVault = storageFixture();
    const newVault = storageFixture('ff'.repeat(32));
    await writeSavedVault(oldVault);
    let replacement: Promise<void> | undefined;
    const originalGet = FakeIDBObjectStore.prototype.get;
    const spy = vi.spyOn(FakeIDBObjectStore.prototype, 'get').mockImplementation(function (this: IDBObjectStore, query) {
      const request = originalGet.call(this, query);
      request.addEventListener('success', () => {
        // Starts another connection at the earliest point after the cleanup
        // read. IDB must serialize its write behind the same transaction's
        // conditional delete; a separate read/delete pair loses this race.
        replacement = writeSavedVault(newVault);
      }, { once: true });
      return request;
    });
    await deleteSavedVault(metadata.publicKey);
    expect(replacement).toBeDefined();
    await replacement;
    spy.mockRestore();
    expect(await readSavedVault()).toEqual(newVault);
  });

  it('allows explicit deletion of corrupt records while key-scoped cleanup preserves them', async () => {
    const corrupt = { corrupted: true };
    await rawWrite(corrupt);
    await deleteSavedVault(metadata.publicKey);
    expect(await readSavedVault()).toEqual(corrupt);
    await deleteSavedVault();
    expect(await readSavedVault()).toBeUndefined();
  });

  it('atomically admits only one concurrent replacement, including two wrappers for the same public key', async () => {
    const old = storageFixture();
    const first = await encryptSignerVaultWithPasskey(key, metadata, descriptor(), secret);
    const second = await encryptSignerVaultWithPasskey(key, metadata, descriptor(), secret);
    await writeSavedVault(old);
    const results = await Promise.all([compareAndSwapSavedVault(old, first), compareAndSwapSavedVault(old, second)]);
    expect(results.filter(Boolean)).toHaveLength(1);
    const winner = results[0] ? first : second;
    expect(await readSavedVault()).toEqual(winner);
    expect(await compareAndSwapSavedVault(old, storageFixture('ff'.repeat(32)))).toBe(false);
    expect(await readSavedVault()).toEqual(winner);
  });

  it('aborts a pending replacement without deleting the legacy vault, and only rolls back its exact committed wrapper', async () => {
    const old = storageFixture(); const next = await encryptSignerVaultWithPasskey(key, metadata, descriptor(), secret);
    await writeSavedVault(old);
    const controller = new AbortController();
    const originalGet = FakeIDBObjectStore.prototype.get;
    const spy = vi.spyOn(FakeIDBObjectStore.prototype, 'get').mockImplementation(function (this: IDBObjectStore, query) {
      const request = originalGet.call(this, query);
      request.addEventListener('success', () => controller.abort(), { once: true });
      return request;
    });
    await expect(compareAndSwapSavedVault(old, next, controller.signal)).rejects.toMatchObject({ name: 'AbortError' });
    spy.mockRestore(); expect(await readSavedVault()).toEqual(old);
    expect(await compareAndSwapSavedVault(old, next)).toBe(true);
    const replacement = await encryptSignerVaultWithPasskey(key, metadata, descriptor(), secret);
    expect(await compareAndSwapSavedVault(next, replacement)).toBe(true);
    expect(await compareAndSwapSavedVault(next, old)).toBe(false); // A late cleanup cannot erase another tab's wrapper.
    expect(await readSavedVault()).toEqual(replacement);
    expect(await compareAndSwapSavedVault(replacement, old)).toBe(true);
    expect(await readSavedVault()).toEqual(old);
  });

  it('preserves an unfamiliar/corrupt concurrent record and does not create a vault after cancellation', async () => {
    const controller = new AbortController(); controller.abort();
    await expect(compareAndSwapSavedVault(undefined, storageFixture(), controller.signal)).rejects.toMatchObject({ name: 'AbortError' });
    expect(await readSavedVault()).toBeUndefined();
    await rawWrite({ unfamiliar: 'preserve' });
    expect(await compareAndSwapSavedVault(undefined, storageFixture())).toBe(false);
    expect(await readSavedVault()).toEqual({ unfamiliar: 'preserve' });
  });
});
